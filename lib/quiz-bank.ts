export type QuestionType = "single" | "multiple" | "boolean";
export type Difficulty = "Easy" | "Medium" | "Hard";
export type BankQuestion = {
  id: string;
  subject: string;
  topic: string;
  type: QuestionType;
  difficulty: Difficulty;
  prompt: string;
  answers: readonly string[];
  correct: readonly number[];
  explanation: string;
  lecture?: string;
  objectiveId?: string;
  cognitiveLevel?: string;
  optionExplanations?: readonly string[];
  sourceRefs?: readonly { file: string; page: number }[];
  status?: "pending_review" | "draft";
  version?: number;
  tags?: readonly string[];
};

function q(
  subject: string,
  id: string,
  topic: string,
  type: QuestionType,
  difficulty: Difficulty,
  prompt: string,
  answers: readonly string[],
  correct: readonly number[],
  explanation: string,
): BankQuestion {
  return {
    id,
    subject,
    topic,
    type,
    difficulty,
    prompt,
    answers,
    correct,
    explanation,
  };
}

