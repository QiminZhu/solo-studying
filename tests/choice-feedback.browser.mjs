import assert from 'node:assert/strict';
import { lecture9Quizzes } from '../lib/quiz-v3/lecture9.ts';
const { chromium } = await import(process.env.SOLO_PLAYWRIGHT_PATH || 'playwright');
const browser = await chromium.launch({ headless: true, executablePath: process.env.SOLO_CHROME_PATH });
const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
const origin = process.env.SOLO_TEST_ORIGIN || 'http://127.0.0.1:5184/solo-studying';
try {
  const bundle = lecture9Quizzes[0];
  const index = bundle.questions.findIndex((item) => item.type === 'single');
  const q = bundle.questions[index];
  assert.ok(q.type === 'single');
  await page.goto(`${origin}/subjects/itcs217/lectures/lecture-9/`);
  const card = page.getByRole('article').filter({ has: page.getByRole('heading', { name: bundle.quiz.title, exact: true }) });
  await card.getByRole('button', { name: 'Start quiz', exact: true }).click();
  await page.waitForURL((url) => url.pathname.replace(/\/$/, '').endsWith('/quizzes/run'));
  for (let i = 0; i < index; i++) await page.getByRole('button', { name: 'Next question', exact: true }).click();
  const wrong = q.answers.findIndex((_, index) => !q.correct.includes(index));
  await page.getByRole('radio', { name: q.answers[wrong], exact: true }).check();
  await page.getByRole('button', { name: 'Check answer', exact: true }).click();
  const result = page.getByRole('region', { name: 'Check result', exact: true });
  await result.waitFor();
  assert.match(await result.innerText(), /Not quite yet/);
  assert.equal(await page.locator('.runner-answer.correct').count(), 0);
  assert.equal(await page.getByText('Correct answer · Not selected', { exact: false }).count(), 0);
  assert.equal(await page.getByText(q.explanation, { exact: true }).count(), 0);
  assert.equal(await page.getByText(q.optionExplanations[q.correct[0]], { exact: true }).count(), 0);
  const explanation = page.getByRole('button', { name: 'Show the explanation', exact: true });
  await explanation.focus();
  await page.keyboard.press('Enter');
  assert.equal(await explanation.getAttribute('aria-expanded'), 'true');
  assert.equal(await page.getByRole('region', { name: 'Explanation', exact: true }).getByText(q.explanation, { exact: true }).isVisible(), true);
  assert.equal(await page.locator('.runner-answer.correct').count(), 0);
  await page.screenshot({ path: '/tmp/solo-feedback-wrong-mobile.png', fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.reload();
  await page.getByRole('region', { name: 'Check result', exact: true }).waitFor();
  assert.match(await result.innerText(), /Not quite yet/);
  assert.equal(await page.locator('.runner-answer.correct').count(), 0);
  assert.equal(await page.getByRole('button', { name: 'Show the explanation', exact: true }).getAttribute('aria-expanded'), 'false');
  await page.getByRole('button', { name: 'Try again', exact: true }).click();
  await page.getByRole('radio', { name: q.answers[q.correct[0]], exact: true }).check();
  await page.getByRole('button', { name: 'Check answer', exact: true }).click();
  assert.match(await result.innerText(), /The first check remains incorrect/);
  assert.equal(await page.locator('.runner-answer.correct').count(), 1);
  assert.match(await page.locator('body').innerText(), /First check: incorrect/);
  console.log('PASS: wrong selection keeps the key hidden, explanation is optional, a later correct try preserves the first check, mobile layout, saved-attempt reload.');
} finally { await browser.close(); }
